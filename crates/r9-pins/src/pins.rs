//! `pins.toml`: every pinned input with its hash (plan 04.1).
//!
//! `r9 sets --write` writes the file, and nobody edits it by hand. The first line holds the
//! SHA-256 of the rest of the file. `r9 check` computes it again, so a hand edit fails the check.

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::path::Path;

/// The name of the file at the root of the repository.
pub const FILE_NAME: &str = "pins.toml";

/// The prefix of the first line, before the digest.
const DIGEST_PREFIX: &str = "# sha256 ";

/// The text after the digest line.
const HEADER: &str = "\
# Written by r9 sets --write from sets.toml and what 9front publishes. Do not edit this file by
# hand: the line above is the SHA-256 of the rest of the file, and r9 check fails when it differs.
";

/// The whole file.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PinsFile {
    /// The time the pins were taken, in UTC, such as `2026-11-09T10:00:00Z`.
    pub as_of: String,
    /// Pinned git trees by name, such as `front`.
    #[serde(default)]
    pub tree: BTreeMap<String, Tree>,
    /// Pinned releases by number, such as `11952`.
    #[serde(default)]
    pub release: BTreeMap<String, Release>,
}

/// A git tree pinned by commit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Tree {
    /// The sets this tree is a member of.
    pub sets: Vec<String>,
    /// The repository on GitHub, as `owner/name`.
    pub repo: String,
    /// The branch the commit is on.
    pub branch: String,
    /// The full commit hash.
    pub commit: String,
    /// The committer date of the commit.
    pub date: String,
}

/// A release: its images and, when found, the commit it was cut from.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Release {
    /// The sets this release is a member of.
    pub sets: Vec<String>,
    /// The name of the release, such as `THIS WAS SUPPOSED TO BE FUN`.
    pub title: String,
    /// The release date, `YYYY-MM-DD`.
    pub date: String,
    /// The announcement page, which gives the SHA-256 of each image.
    pub page: String,
    /// The commit whose tree matches the image's `/sys`, or empty until it is found (plan 01.1).
    #[serde(default)]
    pub commit: String,
    /// The images, one per file.
    pub image: Vec<Image>,
}

/// One release image.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Image {
    /// The file name, such as `9front-11952.amd64.qcow2.gz`.
    pub file: String,
    /// The `objtype` of the image.
    pub objtype: String,
    /// `qcow2` or `iso`.
    pub kind: String,
    /// The SHA-256 of the file, as the announcement page gives it.
    pub sha256: String,
    /// The HTTP URL, when 9front still serves the file over HTTP.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub url: String,
    /// The torrent URL. 9front keeps a torrent for every release, also after the file leaves
    /// the HTTP directory.
    pub torrent: String,
}

impl PinsFile {
    /// Read `pins.toml` from the repository root, or `None` when it does not exist yet.
    pub fn load(root: &Path) -> Result<Option<Self>, String> {
        let path = root.join(FILE_NAME);
        match std::fs::read_to_string(&path) {
            Ok(text) => Self::parse(&text)
                .map(Some)
                .map_err(|e| format!("{}: {e}", path.display())),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(format!("{}: {e}", path.display())),
        }
    }

    /// Parse the text of the file. The digest is not checked here; see [`check_digest`].
    pub fn parse(text: &str) -> Result<Self, String> {
        toml::from_str(text).map_err(|e| e.to_string())
    }

    /// The text of the file, with the digest line first.
    pub fn render(&self) -> Result<String, String> {
        let body = format!(
            "{HEADER}\n{}",
            toml::to_string(self).map_err(|e| e.to_string())?
        );
        Ok(format!("{DIGEST_PREFIX}{}\n{body}", digest(&body)))
    }

    /// Every pin name, trees first.
    #[must_use]
    pub fn names(&self) -> Vec<String> {
        self.tree
            .keys()
            .chain(self.release.keys())
            .cloned()
            .collect()
    }

    /// The problems in the contents: hashes that are not hex of the right length, unknown kinds
    /// and sets, and releases with no image.
    #[must_use]
    pub fn problems(&self, known_sets: &[String]) -> Vec<String> {
        let mut out = Vec::new();
        let set_ok = |name: &str, sets: &[String], out: &mut Vec<String>| {
            if sets.is_empty() {
                out.push(format!("{name}: in no set"));
            }
            for set in sets {
                if !known_sets.iter().any(|k| k == set) {
                    out.push(format!("{name}: set {set} is not in sets.toml"));
                }
            }
        };
        for (name, tree) in &self.tree {
            set_ok(name, &tree.sets, &mut out);
            if !is_hex(&tree.commit, 40) {
                out.push(format!(
                    "{name}: commit {} is not 40 hex digits",
                    tree.commit
                ));
            }
        }
        for (name, release) in &self.release {
            set_ok(name, &release.sets, &mut out);
            if !release.commit.is_empty() && !is_hex(&release.commit, 40) {
                out.push(format!(
                    "{name}: commit {} is not 40 hex digits",
                    release.commit
                ));
            }
            if release.image.is_empty() {
                out.push(format!("{name}: no image"));
            }
            for image in &release.image {
                if !is_hex(&image.sha256, 64) {
                    out.push(format!("{name}: {} has a bad sha256", image.file));
                }
                if image.kind != "qcow2" && image.kind != "iso" {
                    out.push(format!("{name}: {} has kind {}", image.file, image.kind));
                }
                if !image.file.starts_with(&format!("9front-{name}.")) {
                    out.push(format!("{name}: {} is not an image of {name}", image.file));
                }
            }
        }
        out
    }
}

/// Check the digest line of the text of `pins.toml`.
pub fn check_digest(text: &str) -> Result<(), String> {
    let (first, body) = text
        .split_once('\n')
        .ok_or("pins.toml is empty or has one line")?;
    let stated = first
        .strip_prefix(DIGEST_PREFIX)
        .ok_or("the first line of pins.toml is not its digest; write it with r9 sets --write")?;
    let actual = digest(body);
    if stated.trim() == actual {
        Ok(())
    } else {
        Err(format!(
            "pins.toml was edited by hand: its digest is {stated} but its contents hash to {actual}; run r9 sets --write"
        ))
    }
}

/// The SHA-256 of a text, in lower case hex.
#[must_use]
pub fn digest(text: &str) -> String {
    hex(&Sha256::digest(text.as_bytes()))
}

/// Lower case hex of some bytes.
#[must_use]
pub fn hex(bytes: &[u8]) -> String {
    use std::fmt::Write;
    bytes.iter().fold(String::new(), |mut s, b| {
        let _ = write!(s, "{b:02x}");
        s
    })
}

/// Whether a text is `len` lower case hex digits.
#[must_use]
pub fn is_hex(text: &str, len: usize) -> bool {
    text.len() == len && text.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

#[cfg(test)]
mod tests {
    use super::*;

    pub(crate) fn sample() -> PinsFile {
        let mut file = PinsFile {
            as_of: "2026-11-09T10:00:00Z".into(),
            tree: BTreeMap::new(),
            release: BTreeMap::new(),
        };
        file.tree.insert(
            "front".into(),
            Tree {
                sets: vec!["current".into()],
                repo: "9front/9front".into(),
                branch: "front".into(),
                commit: "2859ae04e800737307470538a942ab8f8261253b".into(),
                date: "2026-11-07T22:41:41Z".into(),
            },
        );
        file.release.insert(
            "11952".into(),
            Release {
                sets: vec!["current".into(), "releases".into()],
                title: "THIS WAS SUPPOSED TO BE FUN".into(),
                date: "2026-08-02".into(),
                page: "https://9front.org/releases/2026/08/02/0/".into(),
                commit: String::new(),
                image: vec![Image {
                    file: "9front-11952.amd64.qcow2.gz".into(),
                    objtype: "amd64".into(),
                    kind: "qcow2".into(),
                    sha256: "3c1b57c4b609525e76cb0abac48bc657f71187fd3506674dba4e49b42141729c"
                        .into(),
                    url: "https://9front.org/iso/9front-11952.amd64.qcow2.gz".into(),
                    torrent: "https://9front.org/iso/9front-11952.amd64.qcow2.gz.torrent".into(),
                }],
            },
        );
        file
    }

    #[test]
    fn a_rendered_file_parses_back_and_its_digest_holds() {
        let file = sample();
        let text = file.render().unwrap();
        assert!(text.starts_with("# sha256 "));
        check_digest(&text).unwrap();
        assert_eq!(PinsFile::parse(&text).unwrap(), file);
        assert!(
            file.problems(&["current".into(), "releases".into()])
                .is_empty()
        );
        assert_eq!(file.names(), vec!["front".to_string(), "11952".to_string()]);
    }

    #[test]
    fn a_hand_edit_breaks_the_digest() {
        let text = sample().render().unwrap().replace("2859ae04", "2859ae05");
        let err = check_digest(&text).unwrap_err();
        assert!(err.contains("edited by hand"), "{err}");
        assert!(check_digest("as_of = 1\n").is_err());
    }

    #[test]
    fn bad_contents_are_named() {
        let mut file = sample();
        file.tree.get_mut("front").unwrap().commit = "abc".into();
        let release = file.release.get_mut("11952").unwrap();
        release.image[0].sha256 = "XYZ".into();
        release.image[0].kind = "img".into();
        release.sets = vec!["nightly".into()];
        let problems = file
            .problems(&["current".into(), "releases".into()])
            .join("\n");
        assert!(problems.contains("front: commit abc"), "{problems}");
        assert!(problems.contains("bad sha256"), "{problems}");
        assert!(problems.contains("kind img"), "{problems}");
        assert!(problems.contains("set nightly"), "{problems}");
    }
}
